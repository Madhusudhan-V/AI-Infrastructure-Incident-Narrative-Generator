"""Run Sentinel's complete final validation in one reproducible command.

Usage:
    python -m src.evaluation.final_validation
"""
from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
import time
from pathlib import Path

from src.evaluation.diagnosis_eval import evaluate as evaluate_diagnosis
from src.evaluation.repeated_experiments import run_experiments, summarize
from src.evaluation.run import evaluate


def _markdown_report(test_output, test_passed, baseline, diagnosis, repeated, summaries, args):
    lines = [
        "# Sentinel final validation report",
        "",
        "Generated by `python -m src.evaluation.final_validation`.",
        "",
        "## Validation status",
        "",
        f"- Automated tests: **{'PASS' if test_passed else 'FAIL'}**",
        f"- Synthetic detection benchmark: **{'PASS' if baseline else 'FAIL'}**",
        f"- Cross-signal diagnosis benchmark: **{'PASS' if diagnosis and diagnosis['scenario_count'] > 0 else 'FAIL'}**",
        f"- Repeated anomaly experiments: **{len(repeated)} runs**",
        "",
        "## Automated tests",
        "",
        "```text",
        test_output.strip() or "(No pytest output captured.)",
        "```",
        "",
        "## Controlled synthetic detection benchmark",
        "",
        f"- Event count: {baseline['counts']['total_events']}",
        f"- Healthy latency examples: {baseline['counts']['healthy_latency']}",
        f"- Healthy CPU examples: {baseline['counts']['healthy_cpu']}",
        f"- Rule incidents per scenario: {baseline['counts']['rule_incidents_per_scenario']}",
        f"- ML latency anomalies: {baseline['counts']['ml_anomalies']}",
        "",
        "| Fused actionable metric | Value |",
        "|---|---:|",
    ]
    for key in ("true_positive", "true_negative", "false_positive", "false_negative", "precision", "recall", "f1", "false_positive_rate"):
        lines.append(f"| {key.replace('_', ' ').title()} | {baseline['classification'][key]} |")
    lines += [
        "",
        "| ML signal metric | Value |",
        "|---|---:|",
    ]
    for key in ("true_positive", "true_negative", "false_positive", "false_negative", "precision", "recall", "f1", "false_positive_rate"):
        lines.append(f"| {key.replace('_', ' ').title()} | {baseline['ml_signal'].get(key, 'N/A')} |")
    lines += [
        "",
        "### Scenario metrics caveat",
        "",
        "The current per-scenario slices contain positive examples only. Their false-positive rates are therefore undefined/not informative; use the overall benchmark for the primary fused classification result. Do not interpret the per-scenario rows as standalone accuracy tests.",
        "",
        "## Cross-signal diagnosis",
        "",
        f"- Scenarios: {diagnosis['scenario_count']}",
        f"- Top-1 accuracy: {diagnosis['top1_accuracy']:.1%} ({sum(r['top1_correct'] for r in diagnosis['rows'])}/{diagnosis['scenario_count']})",
        f"- Top-3 accuracy: {diagnosis['top3_accuracy']:.1%}",
        "",
        "| Scenario | Expected label | Top-ranked label | Top-1 correct |",
        "|---|---|---|---:|",
    ]
    for row in diagnosis["rows"]:
        lines.append(f"| {row['scenario']} | {row['expected']} | {row['top1'] or 'None'} | {'Yes' if row['top1_correct'] else 'No'} |")
    lines += [
        "",
        "## Repeated ML sensitivity experiment",
        "",
        f"Configuration: {args.repeats} repeats per contamination setting; contamination values {', '.join(str(v) for v in args.contamination)}; seed start {args.seed_start}. These metrics evaluate the ML anomaly signal, not the fused pipeline.",
        "",
        "| Contamination | Seed | Precision | Recall | F1 | False-positive rate |",
        "|---:|---:|---:|---:|---:|---:|",
    ]
    for row in repeated:
        lines.append(
            f"| {row['contamination']} | {row['seed']} | {row['precision']:.4f} | "
            f"{row['recall']:.4f} | {row['f1']:.4f} | {row['false_positive_rate']:.4f} |"
        )
    lines += [
        "",
        "### Mean and population standard deviation across runs",
        "",
        "| Contamination | Runs | Precision mean ± SD | Recall mean ± SD | F1 mean ± SD | FPR mean ± SD |",
        "|---:|---:|---:|---:|---:|---:|",
    ]
    for row in summaries:
        lines.append(
            f"| {row['contamination']} | {row['runs']} | "
            f"{row['precision_mean']:.4f} ± {row['precision_stdev']:.4f} | "
            f"{row['recall_mean']:.4f} ± {row['recall_stdev']:.4f} | "
            f"{row['f1_mean']:.4f} ± {row['f1_stdev']:.4f} | "
            f"{row['false_positive_rate_mean']:.4f} ± {row['false_positive_rate_stdev']:.4f} |"
        )
    lines += [
        "",
        "## Interpretation and limitations",
        "",
        "- All built-in benchmark results are controlled synthetic results; they are not production accuracy estimates.",
        "- The repeated experiment varies Isolation Forest random seeds and contamination. It is not an independent train/validation/test split.",
        "- The diagnosis benchmark contains a small number of hand-authored labelled scenarios and evaluates a deterministic ranking heuristic.",
        "- Isolation Forest anomaly scores and diagnosis ranking scores are not calibrated probabilities.",
        "- Public-data validation remains a separate research milestone. LogHub includes labelled HDFS and BGL data, but log-only data does not validate CPU/latency-based claims without corresponding metric ground truth.",
        "- Preserve the generated JSON and CSV outputs with your report so the exact configuration and results can be cited.",
        "",
        "## Artifacts",
        "",
        "- `final_validation_results.json`: machine-readable configuration and metrics.",
        "- `final_validation_repeated_runs.csv`: per-seed ML anomaly results.",
        "- `final_validation_report.md`: this report.",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--contamination", type=float, nargs="+", default=[0.03, 0.05])
    parser.add_argument("--seed-start", type=int, default=17)
    parser.add_argument("--output-dir", default="experiments/results/final_validation")
    args = parser.parse_args()
    if args.repeats < 1:
        parser.error("--repeats must be at least 1")
    if not args.contamination or any(not 0 < value <= 0.5 for value in args.contamination):
        parser.error("each contamination value must be greater than 0 and at most 0.5")

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    print("1/4 Running automated tests...")
    test_started = time.perf_counter()
    test = subprocess.run(
        [sys.executable, "-m", "pytest", "-q"],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )
    test_seconds = round(time.perf_counter() - test_started, 3)
    test_output = test.stdout.strip()
    print(test_output or "(No pytest output.)")
    print(f"Test exit code: {test.returncode}; elapsed: {test_seconds}s")

    print("\n2/4 Running the 400-event synthetic detection benchmark...")
    baseline_started = time.perf_counter()
    baseline = evaluate()
    baseline_seconds = round(time.perf_counter() - baseline_started, 3)
    print(f"Events: {baseline['counts']['total_events']}")
    print(f"Fused detection: {baseline['classification']}")
    print(f"ML signal: {baseline['ml_signal']}")
    print(f"Elapsed: {baseline_seconds}s")

    print("\n3/4 Running the cross-signal diagnosis benchmark...")
    diagnosis_started = time.perf_counter()
    diagnosis = evaluate_diagnosis()
    diagnosis_seconds = round(time.perf_counter() - diagnosis_started, 3)
    print(
        f"Top-1: {diagnosis['top1_accuracy']:.1%}; "
        f"Top-3: {diagnosis['top3_accuracy']:.1%}; "
        f"scenarios: {diagnosis['scenario_count']}"
    )
    print(f"Elapsed: {diagnosis_seconds}s")

    print("\n4/4 Running repeated ML sensitivity experiments...")
    repeated_started = time.perf_counter()
    repeated = run_experiments(
        repeats=args.repeats,
        contamination_values=tuple(args.contamination),
        seed_start=args.seed_start,
    )
    summaries = summarize(repeated)
    repeated_seconds = round(time.perf_counter() - repeated_started, 3)
    print("Mean and population standard deviation:")
    for row in summaries:
        print(row)
    print(f"Elapsed: {repeated_seconds}s")

    csv_path = output_dir / "final_validation_repeated_runs.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(repeated[0].keys()))
        writer.writeheader()
        writer.writerows(repeated)

    result = {
        "configuration": {
            "repeats_per_contamination": args.repeats,
            "contamination_values": list(args.contamination),
            "seed_start": args.seed_start,
            "dataset": "controlled synthetic data",
        },
        "automated_tests": {
            "passed": test.returncode == 0,
            "exit_code": test.returncode,
            "elapsed_seconds": test_seconds,
            "output": test_output,
        },
        "baseline_detection": {
            "elapsed_seconds": baseline_seconds,
            "counts": baseline["counts"],
            "classification": baseline["classification"],
            "ml_signal": baseline["ml_signal"],
            "scenario_metrics": baseline["scenario_metrics"],
        },
        "cross_signal_diagnosis": {
            "elapsed_seconds": diagnosis_seconds,
            "scenario_count": diagnosis["scenario_count"],
            "top1_accuracy": diagnosis["top1_accuracy"],
            "top3_accuracy": diagnosis["top3_accuracy"],
            "rows": diagnosis["rows"],
        },
        "repeated_ml_experiments": {
            "elapsed_seconds": repeated_seconds,
            "runs": repeated,
            "summaries": summaries,
        },
    }
    json_path = output_dir / "final_validation_results.json"
    json_path.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    report_path = output_dir / "final_validation_report.md"
    report_path.write_text(
        _markdown_report(test_output, test.returncode == 0, baseline, diagnosis, repeated, summaries, args),
        encoding="utf-8",
    )

    print("\nFINAL VALIDATION SUMMARY")
    print("========================")
    print(f"Automated tests: {'PASS' if test.returncode == 0 else 'FAIL'}")
    print(f"Fused synthetic F1: {baseline['classification']['f1']:.4f}")
    print(f"Fused synthetic recall: {baseline['classification']['recall']:.4f}")
    print(f"Fused synthetic false-positive rate: {baseline['classification']['false_positive_rate']:.4f}")
    print(f"Diagnosis top-1: {diagnosis['top1_accuracy']:.1%}")
    print(f"Diagnosis top-3: {diagnosis['top3_accuracy']:.1%}")
    print(f"Report: {report_path}")
    print(f"JSON: {json_path}")
    print(f"CSV: {csv_path}")

    if test.returncode != 0:
        raise SystemExit(test.returncode)


if __name__ == "__main__":
    main()
